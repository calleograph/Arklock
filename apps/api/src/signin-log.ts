/**
 * Введённое при входе имя попадает в журнал, чтобы по нему разбирать отказы. Но в поле логина люди иногда вставляют
 * пароль, поэтому сохраняется только текст, похожий на имя входа (буквы, цифры, «.», «@», «\\», «_», «-»); остальное
 * заменяется на «***» с длиной: пароль в журнале не оседает.
 */
export function safeLogin(raw: unknown): string {
  const text = String(raw ?? '').trim();
  return /^[\p{L}\p{N}._@\\-]{1,64}$/u.test(text) ? text : text ? `*** (${text.length})` : '';
}
